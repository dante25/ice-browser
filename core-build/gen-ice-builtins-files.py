#!/usr/bin/env python3
"""Generates chrome/browser/extensions/ice_builtins_files.inc.

Lists every file of every Ice built-in (unchanged extension sources from this
repo) with its SHA-256. The browser refuses to load a built-in whose files on
disk differ from this list.

Usage: gen-ice-builtins-files.py <repo root> <output .inc>
"""
import hashlib
import json
import os
import sys

# Directory name under <resources>/ice-builtins/ -> source directory in repo.
BUILTINS = {
    **{d: f"chrome-extensions/{d}" for d in [
        "adblock-for-youtube", "bookmarks-clean-up", "chrome-tab-counter",
        "default-quality-adjuster-for-youtube",
        "enable-right-click-for-google-chrome", "go-back-with-backspace",
        "hide-anything-element-hider-for-chrome",
        "hide-labels-and-end-cards-on-youtube", "multiselect-for-youtube",
        "permanent-progress-bar-for-youtube", "screenshot-youtube",
        "search-by-image", "tab-session-manager", "webmail-ad-blocker",
        "youtube-nonstop"]},
    "ice-shield": "ice-features/ice-shield",
    "google-images-viewer": "ice-features/google-images-viewer",
}


def main():
    repo, out = sys.argv[1], sys.argv[2]
    lines = ["// Generated by core-build/gen-ice-builtins-files.py. Do not edit."]
    for name in sorted(BUILTINS):
        root = os.path.join(repo, BUILTINS[name])
        if not os.path.isfile(os.path.join(root, "manifest.json")):
            sys.exit(f"missing manifest: {root}")
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames.sort()
            for fn in sorted(filenames):
                full = os.path.join(dirpath, fn)
                if os.path.islink(full):
                    sys.exit(f"symlink not allowed: {full}")
                rel = os.path.relpath(full, root).replace(os.sep, "/")
                with open(full, "rb") as f:
                    digest = hashlib.sha256(f.read()).hexdigest()
                lines.append(
                    f"    {{{json.dumps(name)}, {json.dumps(rel)}, \"{digest}\"}},")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
