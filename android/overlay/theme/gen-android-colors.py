#!/usr/bin/env python3
"""Ice palette -> Android resources.
usage: gen-android-colors.py <out dir> [--check <chromium src root>]
Writes <out>/values/ice_colors.xml: replacements for Chromium's static semantic colours (ui/android semantic_colors_non_adaptive.xml: the suffix
_light / _dark is the lightness of the colour itself, so *_dark = text on a light surface) and Material 3 theme overlays ThemeOverlay.Ice.Light / .Dark.
--check <src>: every overridden name must exist in the Chromium sources (res of ui/android, chrome/android): a wrong name would not fail the build but would do nothing."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
pal = json.load(open(os.path.join(HERE, 'ice-palette.json')))
L, D = pal['light'], pal['dark']
# Chromium resource name -> colour. The adaptive names (default_bg_color_baseline ...) point at these, so day and night follow.
OVERRIDES = {
  'default_bg_color_light': L['base'],            'default_bg_color_dark': D['base'],
  'default_bg_color_secondary_light': L['panel'], 'default_bg_color_secondary_dark': D['panel'],
  'default_text_color_dark': L['text'],           'default_text_color_light': D['text'],
  'default_text_color_secondary_dark': L['muted'],'default_text_color_secondary_light': D['muted'],
  'default_text_color_link_dark': L['link'],      'default_text_color_link_light': D['link'],
  'default_text_color_blue_dark': L['link'],      'default_text_color_blue_light': D['link'],
  'default_icon_color_dark': L['text'],           'default_icon_color_light': D['text'],
  'default_icon_color_secondary_dark': L['muted'],'default_icon_color_secondary_light': D['muted'],
  'default_icon_color_blue_dark': L['link'],      'default_icon_color_blue_light': D['link'],
}
def overlay(name, P, parent):
    # Material 3 roles. Desktop: page = panel, inputs = base, cards = card; strong cyan (deep) for switches / focus, links in "link".
    items = {
      'colorPrimary': P['link'], 'colorOnPrimary': '#FFFFFF' if P is L else P['on_accent'],
      'colorPrimaryContainer': P['accent'], 'colorOnPrimaryContainer': P['on_accent'] if P is L else '#E3FDFF',
      'colorSecondaryContainer': P['accent'], 'colorOnSecondaryContainer': P['on_accent'],
      'colorSurface': P['base'], 'colorOnSurface': P['text'], 'colorOnSurfaceVariant': P['muted'],
      'colorSurfaceContainer': P['panel'], 'colorSurfaceContainerHigh': P['card'], 'colorSurfaceContainerHighest': P['card'],
      'colorSurfaceContainerLow': P['base'], 'colorSurfaceContainerLowest': P['base'],
      'colorOutline': P['muted'], 'android:colorBackground': P['base'], 'android:statusBarColor': P['toolbar'],
    }
    body = '\n'.join(f'        <item name="{k}">{v}</item>' for k, v in items.items())
    return f'    <style name="{name}" parent="{parent}">\n{body}\n    </style>\n'
def build():
    names = '\n'.join(f'    <color name="{k}">{v}</color>' for k, v in sorted(OVERRIDES.items()))
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/overlay/theme/gen-android-colors.py from ice-palette.json. Do not edit by hand. -->\n<resources>\n'
            '    <!-- Chromium static semantic colours, Ice values -->\n' + names + '\n\n    <!-- Ice as a Material 3 overlay; the app applies it unless the user picks system (Material You) or a custom colour -->\n'
            + overlay('ThemeOverlay.Ice.Light', L, '') + overlay('ThemeOverlay.Ice.Dark', D, '') + '</resources>\n')
def check(src):
    ok = True; found = set()
    for root, _, files in os.walk(src):
        for f in files:
            if f.endswith('.xml') and '/res' in root + '/':
                for m in re.finditer(r'<color name="([^"]+)"', open(os.path.join(root, f), errors='ignore').read()): found.add(m.group(1))
    for k in OVERRIDES:
        if k not in found: print('MISSING in Chromium sources:', k); ok = False
    print(f'checked {len(OVERRIDES)} names against {len(found)} colour resources:', 'ok' if ok else 'FAILED'); return ok
def patch_text():
    """unified diff for the Chromium src root: adds the colour file and lists it in the resource overlay target of chrome/android/BUILD.gn"""
    xml = build().splitlines()
    new = ''.join('+' + l + '\n' for l in xml)
    return (
      '--- /dev/null\n+++ b/chrome/android/java/res_overlay/values/ice_colors.xml\n@@ -0,0 +1,%d @@\n' % len(xml) + new +
      '--- a/chrome/android/BUILD.gn\n+++ b/chrome/android/BUILD.gn\n@@ -269,6 +269,9 @@\n'
      '   android_resources("java_overlay_resources") {\n'
      '     # Target for overrides of //ui/android:ui_java_resources\n'
      '     resource_overlay = true\n'
      '-    sources = [ "java/res_overlay/values-v33/styles.xml" ]\n'
      '+    sources = [\n'
      '+      "java/res_overlay/values-v33/styles.xml",\n'
      '+      "java/res_overlay/values/ice_colors.xml",\n'
      '+    ]\n'
      '     deps = [ "//ui/android:ui_java_resources" ]\n'
      '   }\n')

if __name__ == '__main__' and len(sys.argv) > 2 and sys.argv[1] == '--patch':
    open(sys.argv[2], 'w').write(patch_text()); print('written', sys.argv[2]); sys.exit(0)
if __name__ == '__main__':
    out = sys.argv[1]; os.makedirs(os.path.join(out, 'values'), exist_ok=True)
    open(os.path.join(out, 'values', 'ice_colors.xml'), 'w').write(build()); print('written', os.path.join(out, 'values', 'ice_colors.xml'))
    if '--check' in sys.argv and not check(sys.argv[sys.argv.index('--check') + 1]): sys.exit(1)
