#!/usr/bin/env python3
"""Ice launcher icons for Android, from assets/icons/ice-1024.png (the desktop icon).
Writes the same files Chromium ships in chrome/android/java/res_chromium_base, at the same pixel sizes:
  mipmap-<dpi>/app_icon.png                    legacy icon (48 dp)
  mipmap-<dpi>/layered_app_icon.png            adaptive icon foreground (108 dp canvas, the artwork inside the 72 dp safe area)
  mipmap-<dpi>/layered_app_icon_background.png adaptive icon background (the dark blue of the artwork)
  drawable/themed_app_icon.xml                 monochrome icon for Android 13 themed icons (a snowflake)
usage: gen-icons.py <repo root> <out dir>   (out dir mirrors the Chromium src tree)"""
import os, sys, math
from PIL import Image
root, out = sys.argv[1], sys.argv[2]
src = Image.open(os.path.join(root, 'assets/icons/ice-1024.png')).convert('RGBA')
DPI = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
BG = (0, 29, 78, 255)       # average dark blue of the artwork
base = os.path.join(out, 'chrome/android/java/res_chromium_base')
for d, k in DPI.items():
    dd = os.path.join(base, 'mipmap-' + d); os.makedirs(dd, exist_ok=True)
    src.resize((round(48 * k),) * 2, Image.LANCZOS).save(os.path.join(dd, 'app_icon.png'), optimize=True)
    canvas = round(108 * k); art = round(70 * k)
    fg = Image.new('RGBA', (canvas, canvas), (0, 0, 0, 0))
    a = src.resize((art, art), Image.LANCZOS); o = (canvas - art) // 2
    fg.alpha_composite(a, (o, o)); fg.save(os.path.join(dd, 'layered_app_icon.png'), optimize=True)
    Image.new('RGBA', (canvas, canvas), BG).save(os.path.join(dd, 'layered_app_icon_background.png'), optimize=True)
# themed icon: six arms with two side branches each, in the 36 dp centre of a 90 dp viewport like Chromium's
paths = []
c, R = 45.0, 17.0
for i in range(6):
    t = math.radians(90 + 60 * i); ex, ey = c + R * math.cos(t), c - R * math.sin(t)
    paths.append(f'M{c:.2f},{c:.2f}L{ex:.2f},{ey:.2f}')
    for f in (0.55, 0.8):
        bx, by = c + R * f * math.cos(t), c - R * f * math.sin(t)
        for s in (-1, 1):
            u = t + s * math.radians(45); L = 5.5 if f == 0.55 else 4.0
            paths.append(f'M{bx:.2f},{by:.2f}L{bx + L * math.cos(u):.2f},{by - L * math.sin(u):.2f}')
xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Ice: monochrome launcher icon (Android 13 themed icons), generated by android/overlay/branding/gen-icons.py -->\n'
       '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="90dp"\n    android:height="90dp"\n'
       '    android:viewportWidth="90"\n    android:viewportHeight="90">\n'
       f'    <path\n        android:pathData="{"".join(paths)}"\n        android:strokeColor="#000000"\n        android:strokeWidth="2.6"\n'
       '        android:strokeLineCap="round"/>\n</vector>\n')
os.makedirs(os.path.join(base, 'drawable'), exist_ok=True)
open(os.path.join(base, 'drawable/themed_app_icon.xml'), 'w').write(xml)
print('icons written to', base)
